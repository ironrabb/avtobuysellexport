type LocaleValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};
const LocaleContext = createContext<LocaleValue>({
  language: "uz",
  setLanguage: () => undefined,
  t: (key) =>
    labels.uz[key] ??
    extraLabels.uz[key] ??
    accountLabels.uz[key] ??
    uploadLabels.uz[key] ??
    key,
});

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem("avto-language");
      return saved === "uz" ||
        saved === "ru" ||
        saved === "en" ||
        saved === "ko"
        ? saved
        : "uz";
    } catch {
      return "uz";
    }
  });
  const setLanguage = (next: Language) => {
    setLanguageState(next);
    try {
      localStorage.setItem("avto-language", next);
    } catch {
      /* Saqlash o‘chirilgan bo‘lsa, joriy sahifadagi til baribir yangilanadi. */
    }
    document.documentElement.lang = next;
  };
  useEffect(() => {
    document.documentElement.lang = language;
    const titles: Record<Language, string> = {
      uz: "Avtomobilingizni toping",
      ru: "Найдите свой автомобиль",
      en: "Find your next car",
      ko: "나에게 맞는 자동차 찾기",
    };
    const descriptions: Record<Language, string> = {
      uz: "Avto.uz — O‘zbekistonda avtomobil sotib olish va sotish uchun qulay platforma.",
      ru: "Avto.uz — удобная платформа для покупки и продажи автомобилей в Узбекистане.",
      en: "Avto.uz is a simple platform to buy and sell cars in Uzbekistan.",
      ko: "Avto.uz는 우즈베키스탄에서 자동차를 사고파는 편리한 플랫폼입니다.",
    };
    document.title = `Avto.uz — ${titles[language]}`;
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute("content", descriptions[language]);
  }, [language]);
  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: (key: string) =>
        labels[language][key] ??
        extraLabels[language][key] ??
        accountLabels[language][key] ??
        uploadLabels[language][key] ??
        labels.uz[key] ??
        extraLabels.uz[key] ??
        accountLabels.uz[key] ??
        uploadLabels.uz[key] ??
        key,
    }),
    [language],
  );
  return (
    <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
  );
}

export function useLocale(): LocaleValue {
  return useContext(LocaleContext);
}
